---@param key string The translation key to check
---@param opts TranslateOptions
---@return boolean Returns true if translation exists, false otherwise
function CheckTranslation(key, opts)

    local l = opts?.lang or lang

    if translations[l][key] then
        return true
    else
        if sx and sx.logger and sx.logger.debug then
            sx.logger:debug( ('[translations] Translation not found for key: %s - Lang: %s'):format( key, l ) )
        end
        return false
    end
end

---@class TranslateOptions
---@field lang string | nil

---@param key string The translation key to retrieve
---@param opts TranslateOptions
---@return string Returns the translated string or error message
function _t(key, opts)

    local l = opts?.lang or lang

    if CheckTranslation(key, opts) then

        return translations[ l ][key]
    else
        return "Translation not found for key: " .. key.. " - Lang: " .. l
    end
end
