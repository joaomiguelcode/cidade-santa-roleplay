---@return chamaleon.shared.GetColours[]
function CHAMALEON_SETTINGS.GetColours()
    local colours = {} ---@type chamaleon.shared.GetColours[]

    for index, data in ipairs(CHAMALEON_SETTINGS.COLORS) do
        colours[index] = {
            id = data.id,
            name = data.translations.name[lang] or data.translations.name["pt-br"],
            gradient = data.gradient,
            colours = data.colours,
        }
    end

    return colours
