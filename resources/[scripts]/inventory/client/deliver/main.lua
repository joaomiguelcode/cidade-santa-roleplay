RegisterCommand("-delivercancel", function()
	if (Starting) then
        Starting = false
        --TriggerEvent("Notify","verde",_t("work_finished"),3000)
		TriggerEvent("Notify2","#finalizaTrabalho")
        TriggerEvent("Notify:Text","")
        
        if DoesBlipExist(Blip) then
            RemoveBlip(Blip)
            Blip = nil
        end
        
        Selected = 1
        Wait(500)
        OnDuty = false
	end
end)

