            tooltip = _t("reward.tooltip.xp_skills")
        }
    },
	dependencies = {},
	flags = eMissionFlags.NONE,
	auto_activate = true,
	coords = PRIMEIRAS_RODAS_PUBLIC_GARAGE_COORDS,
	rewards = {
		skills = { driving = 150 },
