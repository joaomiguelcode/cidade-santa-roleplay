	exports.hud:waypointRemove(waypointId)
end

local function makeGarageWaypoint(coords)
	return {
		coords = coords,
		title = _t("mission.primeiras_rodas.waypoint.garage"),
		indicatorDistance = 30.0,
		markerDistance = 200.0,
		seeThroughWalls = true,
		alwaysVisibleDui = true,
		-- onWaypointEnter = { distance = 5.0, action = waypointRemoveSelf },
	}
end

