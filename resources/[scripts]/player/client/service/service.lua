    for k, v in pairs(List) do
        local Coords = vec3(v[1], v[2], v[3])

        local renderDistance = v[5] or DEFAULT_RENDER_DISTANCE
        local activeDistance = v[6] or DEFAULT_ACTIVE_DISTANCE

        interact.addCoords({
            id = "service:" .. tostring(k),
            coords = Coords,
            options = {
                {
                    label = _t("toggleService"),
                    icon = "building",
                    onSelect = function(data)
                        vSERVER.ToggleService(v[4])
                    end,
                    canInteract = function(entity, distance, coords, id)
                        return true
                    end
                }
            },
            renderDistance = renderDistance,
            activeDistance = activeDistance,
            cooldown = 1500
        })
    end
end

