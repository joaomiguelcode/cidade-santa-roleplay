local EVENTCARGAME_SUBCOMMAND_KEYS = {
    "cmd_announce",
    "cmd_start",
    "cmd_cancel",
    "cmd_accept",
    "cmd_leave",
    "cmd_scores",
    "cmd_schedule",
    "cmd_test",
}

local gEventCargameSubcommandByAlias = nil

local function BuildEventCargameSubcommandAliases()
    local map = {}

    for _, key in ipairs(EVENTCARGAME_SUBCOMMAND_KEYS) do
        for _, langTable in pairs(translations) do
            local value = langTable[key]
            if type(value) == "string" and value ~= "" then
                map[string.lower(value)] = key
            end
        end
    end

    return map
end

---@param raw string|nil
---@return string|nil
function ResolveEventCargameSubcommand(raw)
    if not gEventCargameSubcommandByAlias then
        gEventCargameSubcommandByAlias = BuildEventCargameSubcommandAliases()
    end

    local sub = string.lower(tostring(raw or ""))
    if sub == "" then
        return nil
    end

    return gEventCargameSubcommandByAlias[sub]
end

function CheckTranslation(key)
    if translations[lang] and translations[lang][key] then
        return true
    end
    sx.logger:error(("cargame: traducao ausente key=%s lang=%s"):format(tostring(key), tostring(lang)))
    return false
end

function _t(key, ...)
    if CheckTranslation(key) then
        local str = translations[lang][key]
        if select('#', ...) > 0 then return str:format(...) end
        return str
    end
    return "Translation not found for key: " .. key .. " - Lang: " .. lang
end
