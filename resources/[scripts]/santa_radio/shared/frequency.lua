function GetFrequencyName(frequency)
    local GroupName = Frenquencys[tostring(frequency)]
    local Name = TranslationGroupNames[GroupName]
    if Name then
        return Name
    end

    return GroupName
end
exports('GetFrequencyName', GetFrequencyName)

function NumberOfGroupFrequency(frequency)

    frequency = tostring(frequency)

    local groupName = Frenquencys[ frequency ]

    -- print( ('NumberOfGroupFrequency :: frequency="%s" groupName="%s"'):format( frequency, groupName ) )

    -- print( ('NumberOfGroupFrequency :: gFrenquenciesByGroupName[ groupName ]=%s'):format( json.encode( gFrenquenciesByGroupName[ groupName ] )) )

    if gFrenquenciesByGroupName[ groupName ] then

        for frequencyIndex, freq in ipairs( gFrenquenciesByGroupName[ groupName ] ) do

            if freq == frequency then

                return frequencyIndex
            end
        end

        return -1
    end

    return 0
end
exports('NumberOfGroupFrequency', NumberOfGroupFrequency)

function GetFirstFrequencyGroup(groupName)

    -- print( ('GetFirstFrequencyGroup :: groupName="%s"'):format( groupName ) )

