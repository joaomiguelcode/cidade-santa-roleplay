function sortTableByKeys(t)
    local keys = {}
    for k in pairs(t) do
        table.insert(keys, k)
    end
    table.sort(keys, function(a, b) return tonumber(a) < tonumber(b) end)
    
    local sortedTable = {}
    for _, k in ipairs(keys) do
        table.insert(sortedTable, {key = k, value = t[k]})
    end
    
    return sortedTable
end

---@type table<string, string[]>
local gFrenquenciesByGroupName = { }

do
    local sortedFrenquencies = sortTableByKeys( Frenquencys )

    for _, entry in pairs( sortedFrenquencies ) do

        local frequency, groupName = entry.key, entry.value

        if not gFrenquenciesByGroupName[ groupName ] then

            gFrenquenciesByGroupName[ groupName ] = { }
        end

        table.insert( gFrenquenciesByGroupName[ groupName ], frequency )
    end
end

local TranslationGroupNames = {
