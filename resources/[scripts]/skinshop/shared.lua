local KEY_STATE_PLAYER_UNLOCKED_ITEMS = "PLAYER_UNLOCKED_SPECIAL_CLOTHINGS"

---@param source?
---@return table<string, boolean>
function GetStatePlayerUnlockedItems(source)
    if IsDuplicityVersion() then
        return Player(source).state[KEY_STATE_PLAYER_UNLOCKED_ITEMS] or {}
    end

    return LocalPlayer["state"][KEY_STATE_PLAYER_UNLOCKED_ITEMS] or {}
end

---@param source number
---@param ids string[]
function SetPlayerStateUnlockedClothings(source, ids)
    local clothes = GetStatePlayerUnlockedItems(source)

    for _, id in pairs(ids) do
        clothes[id] = true
    end

    Player(source).state:set(KEY_STATE_PLAYER_UNLOCKED_ITEMS, clothes, true)
end

---@param source number
---@param ids string[]
function RemoveStatePlayerUnlockedClothing(source, ids)
    local clothes = GetStatePlayerUnlockedItems(source)

    for _, id in pairs(ids) do
        clothes[id] = nil
    end

    Player(source).state:set(KEY_STATE_PLAYER_UNLOCKED_ITEMS, clothes, true)
end

exports('SetPlayerStateUnlockedClothings', SetPlayerStateUnlockedClothings)
exports('GetPlayerStateUnlockedClothings', GetStatePlayerUnlockedItems)
exports('RemovePlayerStateUnlockedClothings', RemoveStatePlayerUnlockedClothing)

-- Mapeia items de roupa aos items necessários para desbloqueá-los
-- Formato: [componentType][itemNumber] = "nome_do_item"
ClothingUnlockItems = {}

for _, presets in pairs(SPECIAL_CLOTHING_PRESETS) do
    local unlockItem = presets.unlockItem

    if unlockItem then
        for key, model in pairs(presets) do
            if type(key) == 'number' then
                for componentId, componentData in pairs(model) do
                    ClothingUnlockItems[componentId] = ClothingUnlockItems[componentId] or {}
                    ClothingUnlockItems[componentId][componentData.item] = unlockItem
                end
            end
        end
    end
end

exports('GetSpecialClothingPresets', function()
    return SPECIAL_CLOTHING_PRESETS
end)
